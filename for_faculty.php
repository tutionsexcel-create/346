		<h2>Faculty Frequently Asked Questions</h2>

		<h3>Publishing &amp; Updating Slots</h3>
		
			<h4>1. How far in advance should I publish my availability?</h4>
			<p>We recommend publishing your weekly availability at least <strong>3 to 5 days in advance</strong>. Posting slots early gives students plenty of time to plan their study schedules and keeps your calendar consistently filled.</p>
		
			<h4>2. Can I publish multiple slots on the same day?</h4>
			<p>Yes. You can create as many time slots as you like on a single day. Just be sure to leave a <strong>10-to-15-minute buffer</strong> between back-to-back sessions so you have time to wrap up notes and prepare for your next student.</p>
		
			<h4>3. How do I remove or change an unbooked slot?</h4>
			<p>If a slot still shows a status of <strong>Available</strong>, click the <strong>Remove</strong> button next to that entry in your schedule table. Once removed, it disappears from the student booking page, and you can publish a new time if needed.</p>
		

		<h3>Handling Student Bookings</h3>
		
			<h4>4. How will I know when a student books my slot?</h4>
			<p>As soon as a student reserves your slot, its status in <strong>Your Scheduled Slots</strong> automatically updates from <strong>Available</strong> to <strong>Booked</strong>, and the student's name appears in the <strong>Booked By</strong> column.</p>
		
			<h4>5. Can two students accidentally book the same slot?</h4>
			<p>No. The moment one student confirms a slot, it is immediately locked and removed from the public availability list so no double-bookings can occur.</p>
		
			<h4>6. What if I have an emergency and cannot take a booked session?</h4>
			<p>Because booked slots are locked to protect student schedules, please notify the <strong>Excel Tuitions</strong> coordinator as early as possible (ideally at least <strong>12 hours in advance</strong>) if an unavoidable conflict arises so we can notify the student and help reschedule.</p>
		

		<h3>Attendance &amp; Running Sessions</h3>
		
			<h4>7. When should I join my scheduled session?</h4>
			<p>Please log in and join the session <strong>5 minutes before</strong> the scheduled start time to verify your audio, video, and teaching materials are ready.</p>
		
			<h4>8. How long should I wait if a student is late?</h4>
			<p>Please remain available in the session for the first <strong>10 to 15 minutes</strong>. If the student arrives late, conduct the remainder of the lesson and conclude at the originally scheduled end time so your next session stays on track.</p>
		
			<h4>9. What should I do if a student does not show up?</h4>
			<p>If a student fails to join after <strong>15 minutes</strong>, note the absence in your session log and inform the coordinator so we can follow up with the student or parent.</p>
		
